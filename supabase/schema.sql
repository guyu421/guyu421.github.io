-- 6. 对局表（仅存假先 id、假后 id、时间精确到分、双方结果）
create table public.renju_matches (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on delete cascade default 1,
  round_no integer not null default 1,
  board_no integer not null,
  black_id text not null references public.players(id),
  white_id text not null references public.players(id),
  match_time timestamptz not null default '2026-11-14T08:00:00+08:00',
  result text
);

create or replace function public.set_renju_match_time()
returns trigger
language plpgsql
as $$
begin
  case new.round_no
    when 1 then new.match_time := '2026-11-14T08:00:00+08:00';
    when 2 then new.match_time := '2026-11-14T10:30:00+08:00';
    when 3 then new.match_time := '2026-11-14T14:00:00+08:00';
    when 4 then new.match_time := '2026-11-14T16:30:00+08:00';
    when 5 then new.match_time := '2026-11-15T08:30:00+08:00';
    when 6 then new.match_time := '2026-11-15T13:00:00+08:00';
    when 7 then new.match_time := '2026-11-15T15:30:00+08:00';
    when 8 then new.match_time := '2026-11-15T19:00:00+08:00';
    when 9 then new.match_time := '2026-11-16T08:30:00+08:00';
    else null;
  end case;
  return new;
end;
$$;

drop trigger if exists trg_renju_matches_time on public.renju_matches;
create trigger trg_renju_matches_time
  before insert or update on public.renju_matches
  for each row
  execute function public.set_renju_match_time();

create index if not exists idx_renju_matches_order on public.renju_matches(tournament_id, round_no, board_no);

