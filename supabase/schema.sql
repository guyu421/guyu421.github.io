create or replace function public.set_renju_match_time()
returns trigger
language plpgsql
as $$
begin
  if new.tournament_id = 1 then
    case new.round_no
    when 1 then new.match_time := '2026-11-14T08:00:00+08:00';
    when 2 then new.match_time := '2026-11-14T10:30:00+08:00';
    when 3 then new.match_time := '2026-11-14T14:00:00+08:00';
    when 4 then new.match_time := '2026-11-14T16:30:00+08:00';
    when 5 then new.match_time := '2026-11-15T08:30:00+08:00';
    when 6 then new.match_time := '2026-11-15T13:00:00+08:00';
    when 7 then new.match_time := '2026-11-15T15:30:00+08:00';
    when 8 then new.match_time := '2026-11-15T19:00:00+08:00';
    when 9 then new.match_time := '2026-11-16T08:30:00+08:00';
    else null;
    end case;
  end if;
  return new;
end;
$$;

