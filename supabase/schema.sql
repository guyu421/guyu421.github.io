-- 7. 原子化每日签到函数（北京时间每日一次，+10 源点）
create or replace function public.daily_checkin()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  today_cn date := (now() at time zone 'Asia/Shanghai')::date;
  uname text;
  existing_id bigint;
  prev_date date;
  prev_streak integer;
  new_streak integer;
  new_points integer;
begin
  if uid is null then
    raise exception '请先登录账号';
  end if;

  select id into existing_id
  from public.check_ins
  where user_id = uid and checkin_date = today_cn;

  if existing_id is not null then
    select source_points, streak_days into new_points, new_streak
    from public.user_profiles
    where user_id = uid;

    return jsonb_build_object(
      'alreadyCheckedIn', true,
      'pointsEarned', 0,
      'sourcePoints', coalesce(new_points, 0),
      'streakDays', coalesce(new_streak, 0),
      'checkinDate', today_cn
    );
  end if;

  select coalesce(raw_user_meta_data->>'username', split_part(email, '@', 1), '球友')
  into uname
  from auth.users
  where id = uid;

  select last_checkin_date, streak_days
  into prev_date, prev_streak
  from public.user_profiles
  where user_id = uid;

  if prev_date = today_cn - 1 then
    new_streak := coalesce(prev_streak, 0) + 1;
  else
    new_streak := 1;
  end if;

  insert into public.check_ins (user_id, checkin_date, points_earned)
  values (uid, today_cn, 10);

  insert into public.user_profiles (user_id, username, source_points, streak_days, last_checkin_date, updated_at)
  values (uid, uname, 10, new_streak, today_cn, now())
  on conflict (user_id) do update set
    username = excluded.username,
    source_points = public.user_profiles.source_points + 10,
    streak_days = new_streak,
    last_checkin_date = today_cn,
    updated_at = now()
  returning source_points into new_points;

  return jsonb_build_object(
    'alreadyCheckedIn', false,
    'pointsEarned', 10,
    'sourcePoints', new_points,
    'streakDays', new_streak,
    'checkinDate', today_cn
  );
end;
$$;

grant execute on function public.daily_checkin() to authenticated;

-- 8. 每日首次发表评论自动 +5 源点触发器
create or replace function public.grant_daily_comment_points()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  today_cn date := (now() at time zone 'Asia/Shanghai')::date;
  prev_reward_date date;
begin
  select last_comment_reward_date into prev_reward_date
  from public.user_profiles
  where user_id = new.user_id;

  if not found then
    insert into public.user_profiles (
      user_id, username, source_points, last_comment_reward_date, updated_at
    )
    values (new.user_id, new.username, 5, today_cn, now());
  elsif prev_reward_date is null or prev_reward_date < today_cn then
    update public.user_profiles
    set
      username = new.username,
      source_points = source_points + 5,
      last_comment_reward_date = today_cn,
      updated_at = now()
    where user_id = new.user_id;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_comments_daily_points on public.comments;
create trigger trg_comments_daily_points
  after insert on public.comments
  for each row
  execute function public.grant_daily_comment_points();

-- 9. 每日首次发布文章自动 +50 源点触发器
create or replace function public.grant_daily_article_points()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  today_cn date := (now() at time zone 'Asia/Shanghai')::date;
  prev_reward_date date;
begin
  if new.user_id is null then
    return new;
  end if;

  select last_article_reward_date into prev_reward_date
  from public.user_profiles
  where user_id = new.user_id;

  if not found then
    insert into public.user_profiles (
      user_id, username, source_points, last_article_reward_date, updated_at
    )
    values (
      new.user_id,
      coalesce(
        (select raw_user_meta_data->>'username' from auth.users where id = new.user_id),
        new.author_name
      ),
      50,
      today_cn,
      now()
    );
  elsif prev_reward_date is null or prev_reward_date < today_cn then
    update public.user_profiles
    set
      source_points = source_points + 50,
      last_article_reward_date = today_cn,
      updated_at = now()
    where user_id = new.user_id;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_articles_daily_points on public.articles;
create trigger trg_articles_daily_points
  after insert on public.articles
  for each row
  execute function public.grant_daily_article_points();

