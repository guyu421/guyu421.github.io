-- 赛源网 Supabase 数据库建表与初始数据脚本
-- 请在 Supabase Dashboard -> SQL Editor 中执行

-- 1. 文章表
create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text not null,
  content jsonb not null default '[]'::jsonb,
  category text not null default 'renju',
  category_label text not null default '五子棋',
  cover_image text,
  author_name text not null,
  published_at timestamptz not null default now(),
  read_time_minutes integer not null default 2,
  views integer not null default 0,
  is_featured boolean not null default false,
  is_breaking boolean not null default false,
  source_url text,
  tags jsonb not null default '[]'::jsonb,
  user_id uuid references auth.users(id) on delete set null
);

alter table public.articles
  add column if not exists user_id uuid references auth.users(id) on delete set null;

alter table public.articles
  drop column if exists author_role;

alter table public.articles enable row level security;

drop policy if exists "articles_public_read" on public.articles;
create policy "articles_public_read"
  on public.articles for select
  using (true);

drop policy if exists "articles_auth_insert" on public.articles;
create policy "articles_auth_insert"
  on public.articles for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "articles_owner_delete" on public.articles;
create policy "articles_owner_delete"
  on public.articles for delete
  to authenticated
  using (auth.uid() = user_id);

-- 2. 评论表（关联 Supabase Auth 用户）
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  article_id bigint not null references public.articles(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  content text not null check (char_length(content) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists idx_comments_article_id on public.comments(article_id, id desc);

alter table public.comments enable row level security;

drop policy if exists "comments_public_read" on public.comments;
create policy "comments_public_read"
  on public.comments for select
  using (true);

drop policy if exists "comments_auth_insert" on public.comments;
create policy "comments_auth_insert"
  on public.comments for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "comments_owner_delete" on public.comments;
create policy "comments_owner_delete"
  on public.comments for delete
  to authenticated
  using (auth.uid() = user_id);

-- 授予 anon / authenticated 角色基础表权限
grant usage on schema public to anon, authenticated;
grant select on public.articles to anon, authenticated;
grant insert, delete on public.articles to authenticated;
grant select on public.comments to anon, authenticated;
grant insert, delete on public.comments to authenticated;
grant usage, select on all sequences in schema public to authenticated;

